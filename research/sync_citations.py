#!/usr/bin/env python3
"""
Materialize `citation` entries from research/state.jsonl into paper/references.bib.

Deterministic, stdlib-only. Safe to run repeatedly (dedups by BibTeX key, last entry
in state.jsonl for a given key wins, since the log is append-only = time-ordered).

Usage:
    python3 research/sync_citations.py                 # sync using defaults
    python3 research/sync_citations.py --dry-run        # preview without writing
"""
import argparse
import json
import re
import sys
from pathlib import Path

DEFAULT_STATE = Path(__file__).parent / "state.jsonl"
DEFAULT_BIB = Path(__file__).parent.parent / "paper" / "references.bib"

KEY_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_.:\-]*$")


def load_citations(state_path):
    citations = {}  # key -> {"bibtex":..., "found_for": [...], "date":...}
    with open(state_path) as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                print(f"warning: skipping malformed line {lineno}", file=sys.stderr)
                continue
            if obj.get("type") != "citation":
                continue
            key = obj.get("key")
            bibtex = obj.get("bibtex")
            if not key or not bibtex:
                print(f"warning: line {lineno} is a citation entry missing key/bibtex, skipping", file=sys.stderr)
                continue
            if not KEY_RE.match(key):
                print(f"warning: line {lineno} has a non-BibTeX-safe key '{key}', skipping", file=sys.stderr)
                continue
            entry = citations.setdefault(key, {"found_for": []})
            entry["bibtex"] = bibtex.strip()
            entry["date"] = obj.get("date")
            if obj.get("found_for") and obj["found_for"] not in entry["found_for"]:
                entry["found_for"].append(obj["found_for"])
    return citations


def render_bib(citations):
    lines = [
        "% Auto-generated by research/sync_citations.py from research/state.jsonl `citation` entries.",
        "% Do not hand-edit -- add/fix a `citation` entry in state.jsonl and re-run the script instead,",
        "% otherwise your edit gets clobbered on the next sync.",
        "",
    ]
    for key in sorted(citations):
        entry = citations[key]
        found_for = ", ".join(entry["found_for"]) if entry["found_for"] else "?"
        lines.append(f"% found for: {found_for}" + (f" ({entry['date']})" if entry.get("date") else ""))
        lines.append(entry["bibtex"])
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--state", default=str(DEFAULT_STATE))
    ap.add_argument("--bib", default=str(DEFAULT_BIB))
    ap.add_argument("--dry-run", action="store_true", help="print what would be written, don't touch the file")
    args = ap.parse_args()

    citations = load_citations(args.state)
    if not citations:
        print("No `citation` entries found in state.jsonl -- nothing to sync.")
        return

    content = render_bib(citations)
    if args.dry_run:
        print(content)
        print(f"\n({len(citations)} citation(s), would write to {args.bib})", file=sys.stderr)
        return

    Path(args.bib).write_text(content)
    print(f"Wrote {len(citations)} citation(s) to {args.bib}")


if __name__ == "__main__":
    main()
